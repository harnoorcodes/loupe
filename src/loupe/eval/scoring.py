"""Score the system against known ground truth.

The corpus is generated by us, so we know exactly which defects were planted
and where. That makes recall measurable rather than asserted, which is the
main thing separating this from a demo.

Three outcomes are counted separately, because lumping them together would
be dishonest:

  DETECTED       a planted defect the system found
  MISSED         a planted defect the system did not find
  EXTRA (valid)  a real problem in the corpus that was never planted
  EXTRA (noise)  a finding that corresponds to nothing real

The distinction between the last two matters. The synthetic corpus contains
no tax returns, so reporting them missing is CORRECT, not a false positive.
Counting it as an error would understate the system; counting it as a planted
success would overstate it. It gets its own column.
"""

from __future__ import annotations

from typing import NamedTuple

from loupe.corpus.registry import EXPECTED_GAPS, PLANTED_DEFECTS, PlantedDefect
from loupe.models.finding import Finding
from loupe.observability.logging import get_logger

from loupe.corpus.registry import EXPECTED_GAPS, PLANTED_DEFECTS, PlantedDefect

log = get_logger(__name__)


class DefectResult(NamedTuple):
    """Whether one planted defect was found, and by which finding."""

    defect_id: str
    detected: bool
    finding_id: str | None
    finding_title: str | None


class ScoreCard(NamedTuple):
    """The full result of scoring one run."""

    results: tuple[DefectResult, ...]
    extra_valid: tuple[Finding, ...]
    extra_noise: tuple[Finding, ...]
    total_findings: int

    @property
    def detected_count(self) -> int:
        return sum(1 for r in self.results if r.detected)

    @property
    def planted_count(self) -> int:
        return len(self.results)

    @property
    def recall(self) -> float:
        """Share of planted defects that were found."""
        if not self.results:
            return 0.0
        return self.detected_count / self.planted_count

    @property
    def noise_rate(self) -> float:
        """Share of reported findings that correspond to nothing real."""
        if not self.total_findings:
            return 0.0
        return len(self.extra_noise) / self.total_findings


def _searchable_text(finding: Finding) -> str:
    """All the text of a finding, lowercased, for anchor matching."""
    parts = [finding.title, finding.description]
    parts.extend(span.text for span in finding.all_spans)
    return " ".join(parts).lower()


def matches(finding: Finding, defect: PlantedDefect) -> bool:
    """True if this finding detects this defect.

    Two conditions, both required:

    1. The finding type is one the defect accepts.
    2. At least one anchor appears somewhere in the finding.

    Only ONE anchor is required, not all of them. A finding may quote a
    narrower span than the sentence the defect lives in, so demanding every
    anchor would fail correct detections.
    """
    if finding.finding_type.value not in defect.accepted_types:
        return False
    haystack = _searchable_text(finding)
    return any(anchor.lower() in haystack for anchor in defect.anchors)


def _is_expected_gap(finding: Finding) -> bool:
    """True if this finding reports a document genuinely absent by design."""
    return any(
        finding.finding_id == f"gap-{gap.request_id}" for gap in EXPECTED_GAPS
    )


def score(findings: tuple[Finding, ...]) -> ScoreCard:
    """Compare confirmed findings against the planted defects.

    Args:
        findings: The confirmed findings from a run.

    Returns:
        A ScoreCard with per-defect results and the leftover findings split
        into genuine-but-unplanted and noise.
    """
    results: list[DefectResult] = []
    claimed: set[str] = set()

    for defect in PLANTED_DEFECTS:
        hit: Finding | None = None
        for finding in findings:
            if finding.finding_id in claimed:
                continue
            if matches(finding, defect):
                hit = finding
                break

        if hit is not None:
            claimed.add(hit.finding_id)
            results.append(
                DefectResult(defect.defect_id, True, hit.finding_id, hit.title)
            )
        else:
            results.append(DefectResult(defect.defect_id, False, None, None))

    leftover = [f for f in findings if f.finding_id not in claimed]
    extra_valid = tuple(f for f in leftover if _is_expected_gap(f))
    extra_noise = tuple(f for f in leftover if not _is_expected_gap(f))

    card = ScoreCard(
        results=tuple(results),
        extra_valid=extra_valid,
        extra_noise=extra_noise,
        total_findings=len(findings),
    )

    log.info(
        "scoring complete",
        detected=card.detected_count,
        planted=card.planted_count,
        extra_valid=len(extra_valid),
        noise=len(extra_noise),
    )
    return card


def render(card: ScoreCard) -> str:
    """Format a score card as a markdown report with per-class breakdown."""
    from loupe.corpus.defects import primary_class

    by_id = {d.defect_id: d for d in PLANTED_DEFECTS}
    results_by_id = {r.defect_id: r for r in card.results}

    lines = [
        "# Evaluation",
        "",
        "Measured against a synthetic corpus with defects planted at known",
        "locations, so detection is verified rather than asserted.",
        "",
        "## By defect class",
        "",
        "| Class | Found | Planted | Recall |",
        "| --- | --- | --- | --- |",
    ]

    classes: dict[str, list[str]] = {}
    for defect in PLANTED_DEFECTS:
        classes.setdefault(primary_class(defect), []).append(defect.defect_id)

    for cls, ids in sorted(classes.items()):
        found = sum(1 for i in ids if results_by_id[i].detected)
        pct = f"{found / len(ids):.0%}" if ids else "-"
        label = cls.replace("_", " ")
        lines.append(f"| {label} | {found} | {len(ids)} | {pct} |")

    lines.extend(
        [
            "",
            "## By difficulty",
            "",
            "| Difficulty | Found | Planted | Recall |",
            "| --- | --- | --- | --- |",
        ]
    )

    for level in ("easy", "medium", "hard"):
        ids = [d.defect_id for d in PLANTED_DEFECTS if d.difficulty == level]
        if not ids:
            continue
        found = sum(1 for i in ids if results_by_id[i].detected)
        pct = f"{found / len(ids):.0%}"
        lines.append(f"| {level} | {found} | {len(ids)} | {pct} |")

    lines.extend(
        [
            "",
            "## Every defect",
            "",
            "| Defect | Difficulty | Requires | Detected |",
            "| --- | --- | --- | --- |",
        ]
    )

    for result in card.results:
        defect = by_id[result.defect_id]
        mark = "yes" if result.detected else "no"
        lines.append(
            f"| {defect.defect_id} {defect.name} | {defect.difficulty} | "
            f"{defect.requires} | {mark} |"
        )

    lines.extend(
        [
            "",
            f"**Overall recall: {card.detected_count}/{card.planted_count} "
            f"({card.recall:.0%})**",
            "",
            "## Other findings",
            "",
            f"- {len(card.extra_valid)} genuine absences that were never "
            f"planted. Reporting them is correct behaviour.",
            f"- {len(card.extra_noise)} findings corresponding to nothing real.",
            "",
            f"**Noise rate: {len(card.extra_noise)}/{card.total_findings} "
            f"({card.noise_rate:.0%})**",
            "",
            "## Note",
            "",
            "Four defects are marked hard and are expected to fail against",
            "the current implementation: they need version handling,",
            "coreference resolution, or a three-document reasoning chain.",
            "They are included so the benchmark measures the system rather",
            "than confirming it.",
            "",
        ]
    )
    return "\n".join(lines)